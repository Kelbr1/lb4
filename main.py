def preprocess(text):
    """
    Предварительная обработка текста:
    - перевод в нижний регистр;
    - замена ё на е;
    - удаление знаков препинания;
    - разделение на слова/токены.
    """
    text = text.lower().replace("ё", "е").replace("’", "'")

    # Оставляем слова, числа, дефис внутри слов и десятичные дроби вида 6,5 / 6.5
    tokens = re.findall(
        r"[a-zа-я0-9]+(?:[-'][a-zа-я0-9]+)*(?:[.,](?=\d)[a-zа-я0-9]+)*",
        text
    )
    return tokens

def is_positive_word(word):
    return word in universal_positive_words

def is_negative_word(word):
    return word in universal_negative_words

def is_neutral_word(word):
    if word in neutral_terms_exact:
        return True
    return any(stem in word for stem in neutral_stems)

def add_unique(lst, value):
    if value not in lst:
        lst.append(value)

def mark(indices, tag, value):
    for idx in indices:
        if 0 <= idx < len(tag):
            tag[idx] = value

def get_context_category(noun, adj):
    """
    Проверяет специфичную пару Существительное + Прилагательное.
    Возвращает POS, NEG, NEU или None.
    """
    if noun in context_map:
        if adj in context_map[noun]:
            return context_map[noun][adj]
    return None

def has_sentiment_context(index, tokens, tag, radius=2):
    start = max(0, index - radius)
    end = min(len(tokens), index + radius + 1)

    for j in range(start, end):
        if j == index:
            continue
        if tag[j] in (POS, NEG):
            return True
        if is_positive_word(tokens[j]) or is_negative_word(tokens[j]):
            return True
    return False

