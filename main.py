def classify_review(text):
    tokens = preprocess(text)
    tag = [0] * len(tokens)

    positive = []
    negative = []
    neutral = []

    # 4.1. Сначала ищем готовые словосочетания (фразы)
    for phrase, category in all_phrases:
        phrase_tokens = phrase.split()
        size = len(phrase_tokens)

        if size == 0:
            continue

        for i in range(len(tokens) - size + 1):
            if any(tag[j] != 0 for j in range(i, i + size)):
                continue

            if tokens[i:i + size] == phrase_tokens:
                display = " ".join(tokens[i:i + size])
                
                if category == POS:
                    add_unique(positive, display)
                elif category == NEG:
                    add_unique(negative, display)
                else:
                    add_unique(neutral, display)
                
                mark(range(i, i + size), tag, category)

    # 4.2. Обработка отдельных слов с учетом контекста и соседей
    
    # Итерируем по индексу, чтобы иметь доступ к соседям
    for i, word in enumerate(tokens):
        if tag[i] != 0:
            continue
            
        current_tag = 0
        
        # A. Проверка отрицаний (НЕ + Слово)
        if word in negations and i + 1 < len(tokens):
            next_w = tokens[i+1]
            
            # Если следующее слово уже помечено, пропускаем комбинацию, так как оно обработано выше
            if tag[i+1] != 0:
                continue
                
            if is_positive_word(next_w):
                # Не хороший -> Плохой
                add_unique(negative, f"{word} {next_w}")
                mark([i, i+1], tag, NEG)
                continue
            elif is_negative_word(next_w):
                # Не плохой -> Хороший
                add_unique(positive, f"{word} {next_w}")
                mark([i, i+1], tag, POS)
                continue
            elif is_neutral_word(next_w):
                # Не красный (цвет) -> Может быть нейтрально или контекстно. 
                # Пока оставим нейтральным или пропустим сложную логику, считаем просто описанием отсутствия признака.
                # Но чаще "не нравится" уже покрыто фразами.
                pass 

        # B. Проверка усилителей (Очень + Слово)
        if word in intensifiers and i + 1 < len(tokens):
            next_w = tokens[i+1]
            if tag[i+1] != 0:
                continue
                
            if is_positive_word(next_w):
                add_unique(positive, f"{word} {next_w}")
                mark([i, i+1], tag, POS)
                continue
            elif is_negative_word(next_w):
                add_unique(negative, f"{word} {next_w}")
                mark([i, i+1], tag, NEG)
                continue
        
        # C. Прямое определение категории слова
        cat = None
        if is_positive_word(word):
            cat = POS
        elif is_negative_word(word):
            cat = NEG
        elif is_neutral_word(word):
            cat = NEU
            
        if cat is None:
            continue
            
        # D. Попытка найти контекст (Существительное + Прилагательное)
        # Логика: Если текущее слово - прилагательное (POS/NEG), смотрим на предыдущее и следующее.
        # Если там есть нейтральное существительное, объединяем их в одну характеристику.
        
        found_noun_idx = -1
        found_noun_word = ""
        
        if cat in (POS, NEG):
            # Смотрим назад
            if i > 0 and tag[i-1] == 0 and is_neutral_word(tokens[i-1]):
                found_noun_idx = i - 1
                found_noun_word = tokens[i-1]
            # Смотрим вперед
            elif i + 1 < len(tokens) and tag[i+1] == 0 and is_neutral_word(tokens[i+1]):
                found_noun_idx = i + 1
                found_noun_word = tokens[i+1]
                
            # Дополнительная эвристика: Если нашли существительное, проверяем спец. карту контекста
            if found_noun_idx != -1:
                special_cat = get_context_category(found_noun_word, word)
                if special_cat is not None:
                    # Переопределяем категорию на основе карты
                    cat = special_cat
                    
                # Объединяем в строку вывода
                if found_noun_idx < i:
                    display_str = f"{found_noun_word} {word}"
                    indices_to_mark = [found_noun_idx, i]
                else:
                    display_str = f"{word} {found_noun_word}"
                    indices_to_mark = [i, found_noun_idx]
                    
                if cat == POS:
                    add_unique(positive, display_str)
                elif cat == NEG:
                    add_unique(negative, display_str)
                else: # NEU
                    add_unique(neutral, display_str)
                    
                mark(indices_to_mark, tag, cat)
                continue # Переходим к следующему слову, эти два уже обработаны

        # E. Если контекстного объединения не случилось, добавляем одиночное слово
        if cat == POS:
            add_unique(positive, word)
        elif cat == NEG:
            add_unique(negative, word)
        else: # NEU
            # Для нейтральных слов проверяем, нет ли рядом оценок (чтобы не спамить нейтральными, если они часть оценки)
            if not has_sentiment_context(i, tokens, tag, radius=1):
                 add_unique(neutral, word)
        
        mark([i], tag, cat)

    # 4.3. Определение общей оценки
    p = len(positive)
    n = len(negative)

    if p == 0 and n == 0:
        overall = "нейтральный отзыв"
    elif p > n:
        overall = "положительный отзыв"
    elif n > p:
        overall = "отрицательный отзыв"
    else:
        overall = "смешанный отзыв"

    return positive, negative, neutral, overall

