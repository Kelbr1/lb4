# -----------------------------------------------------

def print_result(positive, negative, neutral, overall):
    print("Положительные характеристики:", ", ".join(positive) if positive else "нет")
    print("Отрицательные характеристики:", ", ".join(negative) if negative else "нет")
    print("Нейтральные характеристики:", ", ".join(neutral) if neutral else "нет")
    print(f"Общая оценка: {overall} (положительных={len(positive)}, отрицательных={len(negative)})")

